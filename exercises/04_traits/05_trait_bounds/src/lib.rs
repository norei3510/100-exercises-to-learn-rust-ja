/// 2つの値のうち小さい方を返します。
pub fn min<T: Ord>(left: T, right: T) -> T {
    // `Ord` は、値が常に比較可能であることを保証します。
    // `PartialOrd` でもコンパイラは満足しますが、異なるセマンティクスになります
    // （比較可能な場合は最小値を返し、比較不能な場合は `right` を返すことになります）。
    if left <= right {
        left
    } else {
        right
    }
}
