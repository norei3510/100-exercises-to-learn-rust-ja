/// 2つの値のうち小さい方を返します。
pub fn min<T: Ord>(left: T, right: T) -> T {
    // `Ord` は、値の比較が可能であることを保証します。
    // `PartialOrd` でもコンパイラは通りますが、セマンティクスが異なります。
    // 比較できない場合は、最小値か `right` のいずれかが返されることになります。
    if left <= right {
        left
    } else {
        right
    }
}
